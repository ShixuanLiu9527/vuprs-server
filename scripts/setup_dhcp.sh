#!/bin/bash

# ------------------------- VUPRS DHCP Config --------------------------------
# Board static address (must also be configured by net_config.sh).
BOARD_IP="${BOARD_IP:-192.168.50.10}"
DHCP_INTERFACE="${DHCP_INTERFACE:-eth0}"
DHCP_POOL_START="${DHCP_POOL_START:-192.168.50.100}"
DHCP_POOL_END="${DHCP_POOL_END:-192.168.50.200}"
DHCP_LEASE="${DHCP_LEASE:-12h}"
# ----------------------------------------------------------------------------

DNSMASQ_CONF="/etc/vuprs-dhcp.conf"
DHCP_SERVICE="/etc/systemd/system/vuprs-dhcp.service"
DHCP_LEASE_FILE="/var/lib/misc/vuprs-dhcp.leases"

RED='\033[1;31m'
GREEN='\033[1;32m'
YELLOW='\033[1;33m'
BLUE='\033[1;34m'
NC='\033[0m'  # No Color

if [[ $EUID -ne 0 ]]; then
    echo -e "${RED}This script must be run as root.${NC}"
    exit 1
fi

DNSMASQ_BIN="$(command -v dnsmasq || true)"
if [ -z "${DNSMASQ_BIN}" ]; then
    echo -e "${RED}dnsmasq not found. Install it first (e.g. apt install dnsmasq).${NC}"
    exit 1
fi

if ! ip link show dev "${DHCP_INTERFACE}" >/dev/null 2>&1; then
    echo -e "${RED}Interface ${DHCP_INTERFACE} not found.${NC}"
    ip -br link
    exit 1
fi

if ! ip -4 addr show dev "${DHCP_INTERFACE}" | grep -q "inet ${BOARD_IP}/"; then
    echo -e "${RED}${BOARD_IP} is not configured on ${DHCP_INTERFACE}.${NC}"
    echo -e "${YELLOW}Run ./net_config.sh first (or set the static IP manually).${NC}"
    exit 1
fi

echo -e "${BLUE}Installing DHCP config for ${DHCP_INTERFACE}:${NC}"
echo -e "  Board IP:   ${GREEN}${BOARD_IP}${NC}"
echo -e "  DHCP pool:  ${GREEN}${DHCP_POOL_START} - ${DHCP_POOL_END}${NC}"
echo -e "  Lease time: ${GREEN}${DHCP_LEASE}${NC}"

mkdir -p "$(dirname "${DHCP_LEASE_FILE}")"

cat > "${DNSMASQ_CONF}" <<EOF
# VUPRS direct-link DHCP (generated by setup_dhcp.sh)
port=0
interface=${DHCP_INTERFACE}
bind-dynamic
dhcp-range=${DHCP_POOL_START},${DHCP_POOL_END},255.255.255.0,${DHCP_LEASE}
dhcp-option=3
dhcp-option=6
dhcp-authoritative
log-dhcp
pid-file=/run/vuprs-dhcp.pid
dhcp-leasefile=${DHCP_LEASE_FILE}
EOF

if command -v systemctl >/dev/null 2>&1; then
    cat > "${DHCP_SERVICE}" <<EOF
[Unit]
Description=VUPRS DHCP server (${DHCP_INTERFACE})
After=network.target

[Service]
Type=simple
ExecStart=${DNSMASQ_BIN} --keep-in-foreground --conf-file=${DNSMASQ_CONF}
Restart=on-failure
RestartSec=2

[Install]
WantedBy=multi-user.target
EOF

    systemctl daemon-reload
    systemctl enable vuprs-dhcp.service
    if systemctl restart vuprs-dhcp.service; then
        sleep 1
        if systemctl is-active --quiet vuprs-dhcp.service; then
            echo -e "${GREEN}DHCP service is running.${NC}"
        else
            echo -e "${RED}DHCP service failed to start. Check: journalctl -u vuprs-dhcp -n 50${NC}"
            exit 1
        fi
    else
        echo -e "${RED}Failed to restart vuprs-dhcp.service.${NC}"
        exit 1
    fi
else
    # No systemd: run dnsmasq directly. This will not survive a reboot.
    if pgrep -f "dnsmasq.*${DNSMASQ_CONF}" >/dev/null 2>&1; then
        pkill -f "dnsmasq.*${DNSMASQ_CONF}"
        sleep 1
    fi
    "${DNSMASQ_BIN}" --conf-file="${DNSMASQ_CONF}"
    echo -e "${YELLOW}systemd not found: dnsmasq started directly. Add it to your init scripts for boot-time startup.${NC}"
fi

if ss -lunp 2>/dev/null | grep -qE ':(67)([[:space:]]|$)'; then
    echo -e "${GREEN}DHCP is listening on UDP 67 (${DHCP_INTERFACE}).${NC}"
else
    echo -e "${YELLOW}Warning: no UDP 67 listener found; check the service log.${NC}"
fi

echo -e "${GREEN}DHCP setup DONE.${NC}"
echo -e "${BLUE}Windows side: keep the Ethernet adapter on automatic DHCP.${NC}"
echo -e "${BLUE}Client target: ${BOARD_IP}:<server port, default 8080>${NC}"
